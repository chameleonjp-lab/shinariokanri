// Original-clause candidates only; all four clauses per case remain not_run.
// F15 checkpoint coverage belongs to a separate test and is not reused here.
async function reader(page: Page) {
  await navigate(page, /^構成/);
  await page.getByRole('tab', { name: '試読・検査', exact: true }).click();
}

async function start(page: Page, entryId: string, drawSeed?: string, versionId = '') {
  await reader(page);
  await page.getByLabel('試読する作品版', { exact: true }).selectOption(versionId);
  await page.getByLabel('試読の開始点', { exact: true }).selectOption(entryId);
  if (drawSeed) await page.getByLabel('抽選種', { exact: true }).fill(drawSeed);
  await page.getByRole('button', { name: /^(試読を始める|この状態から開始し直す)$/ }).click();
}

function card(page: Page, name: string) {
  return page.locator('.coverage-cards > div').filter({ has: page.getByText(name, { exact: true }) });
}

