import { expect, test } from '@playwright/test';
import { createEntity, createProject, textToRichText } from '../../src/domain/model';
import { exportScenario } from '../../src/storage/archive';
import { stageHNarrativeFixture } from '../helpers/stageHNarrative';
import { seed, navigate, backup } from './ap04-original-helpers';

test('same-scene comparison separates route exposure, person belief and author truth', async ({ page }) => {
  const f = stageHNarrativeFixture();
  await seed(page, await exportScenario(f.project)); await navigate(page, /^構成/);
  await page.getByRole('tab', { name: '試読・検査', exact: true }).click();
  await page.getByLabel('試読開始時点の日時', { exact: true }).fill('15');
  await page.getByRole('button', { name: '試読を始める', exact: true }).click();
  await page.locator('.reader-choices').getByRole('button', { name: '直接合流', exact: true }).click();
  const view = page.getByRole('region', { name: '場面ごとの三つの認識', exact: true });
  await expect(view.getByRole('region', { name: '作者が定めた真実', exact: true })).toContainText('作者の確定事実');
  await expect(view.getByRole('region', { name: '選んだ人物の信念', exact: true })).toContainText('取得記録はありません');
  const exposure = view.getByRole('region', { name: '選んだ経路で読者に提示', exact: true });
  await expect(exposure.locator('article').filter({ has: page.getByRole('button', { name: '経路の手掛かり', exact: true }) })).toContainText('この経路では未提示');
  await page.getByRole('button', { name: 'この状態から開始し直す', exact: true }).click();
  await page.locator('.reader-choices').getByRole('button', { name: '手掛かりを経由', exact: true }).click();
  await page.locator('.reader-choices').getByRole('button', { name: '合流へ', exact: true }).click();
  await expect(view.getByRole('region', { name: '選んだ人物の信念', exact: true })).toContainText('本人の誤った信念');
  await expect(exposure.locator('article').filter({ has: page.getByRole('button', { name: '経路の手掛かり', exact: true }) })).toContainText('提示済み');
  await view.getByLabel('比べる人物', { exact: true }).selectOption(f.otherPerson.id);
  await expect(view.getByRole('region', { name: '選んだ人物の信念', exact: true })).toContainText('取得記録はありません');
  await view.getByLabel('比べる人物', { exact: true }).selectOption(f.person.id);
  await expect(view).toContainText('読者の理解は判定しません');
  await exposure.locator('article').filter({ has: page.getByRole('button', { name: '経路の手掛かり', exact: true }) }).getByRole('button', { name: '元の台詞・出来事 · 手掛かりを見る', exact: true }).click();
  await expect(page.locator('.detail-panel')).toContainText('手掛かりを見る');
});

test('presentation move and story-date edit use separate previews and independent undo', async ({ page }) => {
  const project = createProject('回想と日時の操作');
  const first = createEntity(project.projectId, 'chapter', '第1章'), second = createEntity(project.projectId, 'chapter', '第2章');
  const departure = createEntity(project.projectId, 'event', '出発', { time: { mode: 'instant', at: '100', calendarId: project.calendarId } });
  const arrival = createEntity(project.projectId, 'event', '到着', { time: { mode: 'instant', at: '200', calendarId: project.calendarId } });
  departure.data.constraints = [{ type: 'before', targetEventId: arrival.id }];
  const flashback = createEntity(project.projectId, 'scene', '回想', { chapterId: second.id, eventIds: [departure.id, arrival.id], body: textToRichText('回想の本文') });
  second.data.sceneIds = [flashback.id]; project.entities = [first, second, flashback, departure, arrival];
  await seed(page, await exportScenario(project)); await navigate(page, /^構成/);
  const workspace = page.getByRole('region', { name: '物語の構成', exact: true });
  await workspace.getByLabel('変更するもの', { exact: true }).selectOption('presentation', { timeout: 3000 });
  await workspace.getByRole('button', { name: '移す場所を選ぶ', exact: true }).click();
  await workspace.getByLabel('移動先の章', { exact: true }).selectOption(first.id);
  await workspace.getByRole('button', { name: '移動を予告', exact: true }).click();
  await expect(workspace).toContainText('作中の日付は変わりません');
  await workspace.getByRole('button', { name: '確認した場所へ移す', exact: true }).click();
  await expect(workspace.locator(`[data-lane-id="${first.id}"] [data-scene-id="${flashback.id}"]`)).toBeVisible();
  await workspace.getByLabel('変更するもの', { exact: true }).selectOption('world_date');
  await expect(workspace.getByRole('button', { name: '移す場所を選ぶ', exact: true })).toHaveCount(0);
  await workspace.getByRole('button', { name: '到着の作中の日付を変更', exact: true }).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('出来事の日時', { exact: true }).fill('50');
  await editor.getByRole('button', { name: '変更前の影響を確認', exact: true }).click();
  await expect(editor.getByRole('alert')).toContainText('「出発」の後に「到着」');
  await expect(editor.getByRole('button', { name: '差分を一括確定', exact: true })).toBeDisabled();
  await editor.getByLabel('出来事の日時', { exact: true }).fill('300');
  await editor.getByRole('button', { name: '変更前の影響を確認', exact: true }).click();
  await editor.getByRole('button', { name: '差分を一括確定', exact: true }).click();
  await workspace.getByRole('button', { name: '前回の提示順変更を取り消す', exact: true }).click();
  await expect(workspace.locator(`[data-lane-id="${second.id}"] [data-scene-id="${flashback.id}"]`)).toBeVisible();
  await workspace.getByRole('button', { name: '到着の作中の日付を変更', exact: true }).click();
  await expect(editor.getByLabel('出来事の日時', { exact: true })).toHaveValue('300');
  await editor.getByRole('button', { name: '変更を中止', exact: true }).click();
  await workspace.getByRole('button', { name: '前回の作中の日付変更を取り消す', exact: true }).click();
  await expect(workspace.getByRole('button', { name: '前回の作中の日付変更を取り消す', exact: true })).toBeDisabled();
  await expect(workspace).toContainText('作中の日付だけを取り消しました');
  const saved = await backup(page);
  expect(saved.project.entities.find(entity => entity.id === departure.id)?.data).toMatchObject({ time: departure.data.time });
  expect(saved.project.entities.find(entity => entity.id === arrival.id)?.data).toMatchObject({ time: arrival.data.time });
  expect(saved.project.entities.find(entity => entity.id === flashback.id)?.data).toMatchObject({ chapterId: second.id });
});
