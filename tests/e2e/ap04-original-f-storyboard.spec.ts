import { expect, test } from '@playwright/test';
import { createEntity, createProject, textToRichText } from '../../src/domain/model';
import { prepareAsset } from '../../src/domain/attachments';
import { createWorldSnapshot } from '../../src/domain/world';
import { exportScenario } from '../../src/storage/archive';
import { attachGiven, attachObservation, backup, navigate, openEntity, seed } from './ap04-original-helpers';
import { onePixelPng } from './ap04-original-f-assets';

// Budget for multi-step UI/cold/file checks; original acceptance limits stay unchanged.
test.setTimeout(180_000);

test('AT-F53 世界tick -10と演出1000msを別に保持し、コマから対象台詞へ戻り、参考画像だけを完成素材に差替える', async ({ page }, info) => {
  let p = createProject('AT-F53 世界日時と演出ms');
  const event = createEntity(p.projectId, 'event', '世界tick -10の出来事', { time: { mode: 'instant', at: '-10', calendarId: p.calendars[0].id } });
  const line = createEntity(p.projectId, 'dialogue_line', 'コマの対象台詞', { text: textToRichText('対象台詞の本文。') });
  const scene = createEntity(p.projectId, 'scene', 'コマを確認する場面', { body: textToRichText('世界の日付と演出の秒数は別。'), dialogueLineIds: [line.id], eventIds: [event.id] });
  const chapter = createEntity(p.projectId, 'chapter', 'コマの章', { sceneIds: [scene.id] }); scene.data.chapterId = chapter.id;
  const reference = await prepareAsset(onePixelPng(200, 40, 40), '赤い参考画像.png');
  const finalMaterial = await prepareAsset(onePixelPng(40, 40, 200), '青い完成素材.png');
  const { bytes: referenceBytes, preview: _referencePreview, ...metadata } = reference;
  const image = createEntity(p.projectId, 'attachment', '参考画像', { ...metadata, stage: 'reference' });
  const anchor = { entityId: line.id, blockId: line.data.text[0].id, start: 0, end: 2 };
  const frame = createEntity(p.projectId, 'storyboard_frame', '1000msの確認コマ', { anchor, mediaStartMs: 1000, mediaEndMs: 2000, referenceAssetId: image.id, caption: textToRichText('参考画像を使った台詞のコマ。') });
  const cue = createEntity(p.projectId, 'cue', '1000msからの演出', { anchor, cueType: 'camera', mediaTime: 1000, waitMs: 250 }); line.data.cueIds = [cue.id];
  p.entities.push(event, line, scene, chapter, image, frame, cue);
  p.entities.forEach(e => { e.status = 'confirmed'; });
  p = await createWorldSnapshot(p, '参考画像の旧固定版');
  const oldPin = p.snapshots.at(-1)!;
  const bytes = await exportScenario(p, { loadAsset: hash => hash === reference.contentHash ? referenceBytes : undefined });
  await attachGiven(info, 'AT-F53', bytes, { eventId: event.id, worldTick: '-10', lineId: line.id, bodyBlockId: line.data.text[0].id, frameId: frame.id, mediaStartMs: 1000, cueId: cue.id, cueMediaTime: 1000, referenceAttachmentId: image.id, referenceHash: reference.contentHash, pinnedSnapshotId: oldPin.id });
  await seed(page, bytes); await navigate(page, /^構成/);
  await page.getByRole('tab', { name: '章の試読', exact: true }).click();
  const reading = page.getByRole('region', { name: '章順・選択経路の通読', exact: true });
  await reading.getByLabel('章試読の世界内tick', { exact: true }).fill('-10');
  await reading.getByRole('button', { name: '記録付き読書を始める', exact: true }).click();
  await reading.getByRole('button', { name: '次の場面を提示', exact: true }).click();
  await reading.getByLabel('演出・絵コンテを表示', { exact: true }).check();
  const presentedFrame = reading.locator('.presentation-cues article').filter({ has: page.getByRole('heading', { name: frame.name, exact: true }) });
  await expect(presentedFrame).toContainText('絵コンテ 1000〜2000 ms');
  await expect(reading.locator('.presentation-cues')).toContainText('演出 1000 ms');
  await presentedFrame.getByRole('button', { name: '演出の本文位置を開く', exact: true }).click();
  const editor = page.locator('.detail-panel');
  await expect(editor.locator('h2')).toHaveText(line.name);
  await expect(editor.getByRole('textbox', { name: '台詞', exact: true })).toHaveValue('対象台詞の本文。');

  await openEntity(page, 'attachment', image.name);
  const tools = page.locator('.production-tools'); await tools.locator('summary').click();
  await tools.getByLabel('素材ファイルを選ぶ', { exact: true }).setInputFiles({ name: '青い完成素材.png', mimeType: 'image/png', buffer: Buffer.from(finalMaterial.bytes) });
  await tools.getByRole('checkbox', { name: frame.name, exact: true }).check();
  await tools.getByRole('button', { name: '変更の影響を確認', exact: true }).click();
  await expect(tools).toContainText('差替える参照 1件');
  await tools.getByRole('button', { name: '確認した変更を保存', exact: true }).click();
  await expect(tools.getByRole('status').filter({ hasText: '表示版を確認' })).toBeVisible();
  const replaced = await backup(page);
  const material = replaced.project.entities.find(e => e.kind === 'attachment' && e.data.revisionHistory?.includes(image.id));
  expect(material?.kind).toBe('attachment');
  if (!material || material.kind !== 'attachment') throw new Error('差替えた新素材がありません');
  expect(replaced.project.entities.find(e => e.id === frame.id)).toMatchObject({ status: 'needs_review', data: { referenceAssetId: material.id, mediaStartMs: 1000, mediaEndMs: 2000 } });
  await openEntity(page, 'attachment', material.name);
  await editor.getByLabel('素材の状態', { exact: true }).selectOption('final');
  await editor.getByLabel('情報の状態', { exact: true }).selectOption('confirmed');
  await editor.locator('.editor-footer').getByRole('button', { name: '保存する', exact: true }).click();
  await expect(editor.locator('.editor-save-state')).toContainText('端末内保存済み');
  await openEntity(page, 'storyboard_frame', frame.name);
  await editor.getByLabel('参考素材', { exact: true }).selectOption('');
  await editor.getByLabel('完成素材', { exact: true }).selectOption(material.id);
  await editor.locator('.editor-footer').getByRole('button', { name: '保存する', exact: true }).click();
  await expect(editor.locator('.editor-save-state')).toContainText('端末内保存済み');
  await expect(editor.getByLabel('情報の状態', { exact: true })).toHaveValue('needs_review');
  await page.reload();
  const saved = await backup(page);
  expect(saved.project.entities.find(e => e.id === event.id)?.data).toEqual(event.data);
  expect(saved.project.entities.find(e => e.id === line.id)?.data).toEqual(line.data);
  expect(saved.project.entities.find(e => e.id === cue.id)?.data).toEqual(cue.data);
  expect(saved.project.entities.find(e => e.id === frame.id)).toMatchObject({ status: 'needs_review', data: { anchor, mediaStartMs: 1000, mediaEndMs: 2000, finalAssetId: material.id, caption: frame.data.caption } });
  expect(saved.project.entities.find(e => e.id === image.id)?.data).toEqual(image.data);
  expect(saved.project.snapshots.find(s => s.id === oldPin.id)).toEqual(oldPin);
  expect(saved.assets.map(a => a.contentHash).sort()).toEqual([reference.contentHash, finalMaterial.contentHash].sort());
  expect(saved.assets.find(a => a.contentHash === reference.contentHash)?.bytes).toEqual(reference.bytes);
  expect(saved.assets.find(a => a.contentHash === finalMaterial.contentHash)?.bytes).toEqual(finalMaterial.bytes);
  await openEntity(page, 'event', event.name);
  await expect(editor.getByLabel('世界内tick', { exact: true })).toHaveValue('-10');
  await openEntity(page, 'storyboard_frame', frame.name);
  await expect(editor.getByLabel('開始（ms）', { exact: true })).toHaveValue('1000');
  await expect(editor.getByLabel('情報の状態', { exact: true })).toHaveValue('needs_review');
  await attachObservation(info, 'AT-F53-observed', { worldTick: '-10', frameId: frame.id, mediaStartMs: 1000, cueId: cue.id, cueMediaTime: 1000, retainedReferenceAttachmentId: image.id, finalAttachmentId: material.id, oldSnapshotId: oldPin.id, assetHashes: [reference.contentHash, finalMaterial.contentHash], frameNeedsReviewAfterMaterialOnlyReplacement: true, lineAndWorldTimeUnchanged: true, revision: saved.project.revision });
});
