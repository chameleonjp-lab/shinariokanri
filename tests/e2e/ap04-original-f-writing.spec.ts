  await expect(structure).toContainText('緊張度 2/3件を集計。未入力 1件は空欄のまま');
  await page.getByRole('button', { name: '別案を新しい版として保存', exact: true }).click();
  await expect(page.getByText('保存済み 2版', { exact: true })).toBeVisible();
