  await structure.getByRole('button', { name: '順序の差分を確認', exact: true }).click();
  const preview = structure.getByRole('region', { name: '構成順の差分', exact: true });
  await expect(preview).toContainText('変更前：緊張度2の場面 → 緊張度8の場面 → 緊張度未入力の場面');
  await expect(preview).toContainText('変更後：緊張度未入力の場面 → 緊張度8の場面 → 緊張度2の場面');
  expect(await authorFingerprint(page)).toBe(beforePreview);
  await preview.getByRole('button', { name: '取消', exact: true }).click();
  expect(await authorFingerprint(page)).toBe(beforePreview);
  await structure.getByRole('button', { name: '順序の差分を確認', exact: true }).click();
  await preview.getByRole('button', { name: '別案の下書きへ適用', exact: true }).click();
