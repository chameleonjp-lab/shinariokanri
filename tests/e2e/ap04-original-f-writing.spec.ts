  const eight = createEntity(p.projectId, 'scene', '緊張度8の場面', { chapterId: chapter.id, body: textToRichText('作者が付けた高い緊張度。'), tension: 8 });
  const missing = createEntity(p.projectId, 'scene', '緊張度未入力の場面', { chapterId: chapter.id, body: textToRichText('緊張度をまだ決めていない。'), tension: null });
  chapter.data.sceneIds = [two.id, eight.id, missing.id];
  p.entities.push(chapter, two, eight, missing);
  const bytes = await exportScenario(p);
  await attachGiven(info, 'AT-F05', bytes, { chapterId: chapter.id, canonicalOrder: chapter.data.sceneIds, tensionValues: [2, 8, null], structureTemplate: { id: 'three-part', beats: ['導入', '展開', '結末'] } });
