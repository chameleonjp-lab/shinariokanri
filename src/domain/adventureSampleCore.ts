/** Adds prose and dialogue to the original twelve scenes, before enrichment. */
export function enrichAdventureCore(project: ProjectData): void {
  const scenes = getEntitiesByKind(project, 'scene');
  const people = getEntitiesByKind(project, 'character');
  for (const expansion of CORE_SCENES) {
    const scene = scenes.find(candidate => candidate.name.endsWith(`　${expansion.title}`));
    if (!scene || scene.data.body.length !== 3) throw new Error(`基本場面が見つからないか、既に拡充されています: ${expansion.title}`);
    scene.data.body.splice(2, 0, ...textToRichText(expansion.paragraphs.join('\n')));
    for (const [speakerName, text] of expansion.lines) {
      const speaker = people.find(person => person.name === speakerName);
      if (!speaker) throw new Error(`基本場面の発話者が見つかりません: ${speakerName}`);
      const line = createEntity(project.projectId, 'dialogue_line', `${expansion.title}・${speakerName}`, {
        speakerId: speaker.id, text: textToRichText(text),
      });
      line.status = 'confirmed';
      project.entities.push(line);
      scene.data.dialogueLineIds = [...(scene.data.dialogueLineIds ?? []), line.id];
    }
  }
}
